const BY_SITE = new Map<string, CraigslistSite>();
for (const site of CRAIGSLIST_SITES) if (!BY_SITE.has(site.site)) BY_SITE.set(site.site, site);

export function findCraigslistSite(site: string): CraigslistSite | undefined {
  return BY_SITE.get(site.trim().toLowerCase());
}

type NearestSite = { site: CraigslistSite; distanceKm: number };

/**
 * The known site closest to a point, with its distance. Sites in the point's own country win
 * whenever one is within MAX_SITE_DISTANCE_KM, even if a site across the border is nearer: a
 * border town's buyers, prices and currency belong to its own side.
 */
export function nearestCraigslistSite(point: { lat: number; lng: number; countryCode?: string | null }): NearestSite | undefined {
  if (!Number.isFinite(point.lat) || !Number.isFinite(point.lng)) return undefined;
  const country = point.countryCode?.trim().toUpperCase();
  let best: NearestSite | undefined;
  let bestDomestic: NearestSite | undefined;
  for (const site of CRAIGSLIST_SITES) {
    const distanceKm = haversineKm(point, site);
    if (!best || distanceKm < best.distanceKm) best = { site, distanceKm };
    if (site.countryCode === country && (!bestDomestic || distanceKm < bestDomestic.distanceKm)) {
      bestDomestic = { site, distanceKm };
    }
  }
  return bestDomestic && bestDomestic.distanceKm <= MAX_SITE_DISTANCE_KM ? bestDomestic : best;
}
